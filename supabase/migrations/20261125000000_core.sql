-- Switchyard core storage: projects, connections, path graph, check results.
--
-- SECURITY MODEL
-- The API connects as `postgres` and, inside every data-access transaction, runs:
--   set local role switchyard_api;
--   select set_config('switchyard.user_id', '<uuid>', true);
-- RLS (enabled AND forced) on every table then restricts rows to that user. The API also
-- filters by user_id explicitly in each query (defense in depth).

-- 1. Least-privilege role -------------------------------------------------------------------
-- NOLOGIN: it can only be reached through `set role`. No password is stored here.
-- NOINHERIT / NOBYPASSRLS: it never gains other privileges and is always subject to RLS.
-- In production an operator may instead run
--   alter role switchyard_api login password '<secret>';
-- and connect with it directly (set the password outside of version control).
do $$
begin
  if not exists (select from pg_roles where rolname = 'switchyard_api') then
    create role switchyard_api nologin noinherit nobypassrls;
  end if;
end
$$;

-- Lets the API's `postgres` connection `set role switchyard_api` (also needed on hosted Supabase).
grant switchyard_api to postgres;

-- 2. Current-user helper --------------------------------------------------------------------
-- Reads the user id set by the API for this transaction; NULL when unset or empty, so that
-- policies match no row (fail closed).
create or replace function switchyard.current_user_id()
returns uuid
language sql
stable
security invoker
set search_path = ''
as $$
  select nullif(pg_catalog.current_setting('switchyard.user_id', true), '')::uuid
$$;

revoke all on function switchyard.current_user_id() from public;
grant execute on function switchyard.current_user_id() to switchyard_api;

-- updated_at trigger function.
create or replace function switchyard.touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = pg_catalog.now();
  return new;
end
$$;

revoke all on function switchyard.touch_updated_at() from public;
grant execute on function switchyard.touch_updated_at() to switchyard_api;

-- 3. Tables ---------------------------------------------------------------------------------
create table switchyard.projects (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Target for composite FKs: children can only reference a project of the same user.
  unique (id, user_id)
);
create index projects_user_id_idx on switchyard.projects (user_id);

create table switchyard.connections (
  -- No default: generated by the app because it is bound into the encryption AAD.
  id uuid primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  project_id uuid not null,
  integration_id text not null check (integration_id ~ '^[a-z0-9][a-z0-9-]{0,63}$'),
  label text not null check (char_length(label) between 1 and 100),
  config jsonb not null default '{}' check (jsonb_typeof(config) = 'object'),
  secrets text check (secrets is null or char_length(secrets) <= 16384),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (project_id, user_id)
    references switchyard.projects (id, user_id) on delete cascade,
  unique (id, project_id)
);
create index connections_project_id_idx on switchyard.connections (project_id);

create table switchyard.path_nodes (
  project_id uuid not null,
  id uuid not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  connection_id uuid null,
  integration_id text not null check (integration_id ~ '^[a-z0-9][a-z0-9-]{0,63}$'),
  label text not null check (char_length(label) between 1 and 100),
  primary key (project_id, id),
  foreign key (project_id, user_id)
    references switchyard.projects (id, user_id) on delete cascade,
  -- Deleting a connection keeps the node but detaches it (project_id stays set).
  foreign key (connection_id, project_id)
    references switchyard.connections (id, project_id) on delete set null (connection_id)
);

create table switchyard.path_edges (
  project_id uuid not null,
  id uuid not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  from_node uuid not null,
  to_node uuid not null,
  label text null check (label is null or char_length(label) between 1 and 100),
  primary key (project_id, id),
  check (from_node <> to_node),
  unique (project_id, from_node, to_node),
  foreign key (project_id, user_id)
    references switchyard.projects (id, user_id) on delete cascade,
  foreign key (project_id, from_node)
    references switchyard.path_nodes (project_id, id) on delete cascade,
  foreign key (project_id, to_node)
    references switchyard.path_nodes (project_id, id) on delete cascade
);

create table switchyard.check_results (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  project_id uuid not null,
  connection_id uuid not null,
  check_id text not null check (char_length(check_id) between 1 and 100),
  status text not null check (status in ('ok', 'warning', 'error', 'unknown')),
  message text not null check (char_length(message) <= 2000),
  details jsonb null,
  checked_at timestamptz not null,
  foreign key (project_id, user_id)
    references switchyard.projects (id, user_id) on delete cascade,
  foreign key (connection_id, project_id)
    references switchyard.connections (id, project_id) on delete cascade
);
create index check_results_conn_check_idx
  on switchyard.check_results (connection_id, check_id, checked_at desc);

create trigger projects_touch_updated_at
  before update on switchyard.projects
  for each row execute function switchyard.touch_updated_at();
create trigger connections_touch_updated_at
  before update on switchyard.connections
  for each row execute function switchyard.touch_updated_at();

-- 4. Row level security ---------------------------------------------------------------------
-- FORCE applies RLS even to the table owner; only the policy below grants access, and only to
-- switchyard_api. No policy exists for any other role.
do $$
declare
  t text;
begin
  foreach t in array array['projects', 'connections', 'path_nodes', 'path_edges', 'check_results']
  loop
    execute format('alter table switchyard.%I enable row level security', t);
    execute format('alter table switchyard.%I force row level security', t);
    execute format(
      'create policy %I on switchyard.%I for all to switchyard_api '
      'using (user_id = switchyard.current_user_id()) '
      'with check (user_id = switchyard.current_user_id())',
      t || '_owner', t);
  end loop;
end
$$;

-- 5. Privileges -----------------------------------------------------------------------------
revoke all on switchyard.projects, switchyard.connections, switchyard.path_nodes,
  switchyard.path_edges, switchyard.check_results from anon, authenticated, public;
revoke all on sequence switchyard.check_results_id_seq from anon, authenticated, public;

grant usage on schema switchyard to switchyard_api;
grant select, insert, update, delete on switchyard.projects, switchyard.connections,
  switchyard.path_nodes, switchyard.path_edges, switchyard.check_results to switchyard_api;
grant usage on sequence switchyard.check_results_id_seq to switchyard_api;

-- 6. Documentation --------------------------------------------------------------------------
comment on table switchyard.projects is 'User projects; root of all per-user data.';
comment on table switchyard.connections is
  'Integration connections of a project (non-secret config plus encrypted secrets).';
comment on column switchyard.connections.secrets is
  'AES-256-GCM ciphertext of secret credential fields, never returned by the API';
comment on table switchyard.path_nodes is 'Nodes of a project path graph, optionally bound to a connection.';
comment on table switchyard.path_edges is 'Directed edges between path nodes of a project.';
comment on table switchyard.check_results is 'History of integration check results per connection.';
