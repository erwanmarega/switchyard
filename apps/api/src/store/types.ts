import type { CheckStatus } from '@switchyard/plugin-sdk'

export type { CheckStatus }

/** Records returned by the store: camelCase, timestamps as ISO strings. Never contain secrets. */
export interface ProjectRecord {
  id: string
  name: string
  createdAt: string
  updatedAt: string
}

export interface ConnectionRecord {
  id: string
  projectId: string
  integrationId: string
  label: string
  /** Non-secret credential fields. */
  config: Record<string, string>
  /** True when sealed secrets are stored. The ciphertext itself is never exposed here. */
  hasSecrets: boolean
  createdAt: string
  updatedAt: string
}

export interface NewConnection {
  /** Generated by the app before sealing: it is bound into the encryption AAD. */
  id: string
  integrationId: string
  label: string
  config: Record<string, string>
  /** Sealed ciphertext, or null when the integration has no secret field. */
  secrets: string | null
}

export interface ConnectionPatch {
  label?: string
  /** Both must be provided together: credentials are replaced as a whole. */
  credentials?: { config: Record<string, string>; secrets: string | null }
}

export interface PathNodeRecord {
  id: string
  integrationId: string
  label: string
  connectionId: string | null
}

export interface PathEdgeRecord {
  id: string
  from: string
  to: string
  label?: string
}

export interface PathRecord {
  nodes: PathNodeRecord[]
  edges: PathEdgeRecord[]
}

export const LIMITS = {
  projectsPerUser: 100,
  connectionsPerProject: 50,
  nodesPerPath: 200,
  edgesPerPath: 500,
} as const

/** A per-user quota was reached (mapped to 409). */
export class LimitError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'LimitError'
  }
}

/** Data rejected by a store-level check (mapped to 400). `path` never contains input values. */
export class ValidationError extends Error {
  constructor(
    readonly path: string,
    message: string,
  ) {
    super(message)
    this.name = 'ValidationError'
  }
}

/** Connection data loaded by the check runner. Holds the sealed secrets: never send it anywhere. */
export interface RunnableConnection {
  id: string
  projectId: string
  integrationId: string
  config: Record<string, string>
  /** Sealed ciphertext, or null when the integration has no secret field. */
  secrets: string | null
}

/** A sanitized check result, ready to store (secrets already redacted by the runner). */
export interface NewCheckResult {
  checkId: string
  status: CheckStatus
  message: string
  details: Record<string, unknown> | null
  /** ISO 8601. */
  checkedAt: string
}

export interface CheckResultRecord extends NewCheckResult {
  connectionId: string
}

/** A connection claimed by the scheduler: ids only, never secrets. */
export interface DueConnection {
  userId: string
  projectId: string
  connectionId: string
}

/**
 * SYSTEM-level access used only by the check scheduler. It is the single place that crosses users,
 * and it only ever returns ids (through SECURITY DEFINER functions in the database).
 */
export interface SchedulerStore {
  /**
   * Atomically claims up to `limit` connections whose next check is due (at most `perUser` per
   * user, so one user cannot starve the others) and pushes their next check `intervalSeconds`
   * later, so concurrent API instances never claim the same connection.
   */
  claimDueConnections(
    limit: number,
    intervalSeconds: number,
    perUser: number,
  ): Promise<DueConnection[]>
  /** Deletes check results older than `olderThanDays`. Returns the number of deleted rows. */
  pruneCheckResults(olderThanDays: number): Promise<number>
}

/**
 * User-scoped data access. Every method takes the authenticated user id first and only ever
 * touches that user's rows. "Not found" (missing or owned by someone else) is `null`/`false`.
 */
export interface Store {
  listProjects(userId: string): Promise<ProjectRecord[]>
  getProject(userId: string, projectId: string): Promise<ProjectRecord | null>
  /** Throws `LimitError` past the per-user project quota. */
  createProject(userId: string, name: string): Promise<ProjectRecord>
  updateProject(userId: string, projectId: string, name: string): Promise<ProjectRecord | null>
  deleteProject(userId: string, projectId: string): Promise<boolean>

  /** Null when the project does not exist. */
  listConnections(userId: string, projectId: string): Promise<ConnectionRecord[] | null>
  getConnection(
    userId: string,
    projectId: string,
    connectionId: string,
  ): Promise<ConnectionRecord | null>
  /** Null when the project does not exist. Throws `LimitError` past the per-project quota. */
  createConnection(
    userId: string,
    projectId: string,
    input: NewConnection,
  ): Promise<ConnectionRecord | null>
  updateConnection(
    userId: string,
    projectId: string,
    connectionId: string,
    patch: ConnectionPatch,
  ): Promise<ConnectionRecord | null>
  /** Nodes bound to the connection are detached (`connectionId` becomes null). */
  deleteConnection(userId: string, projectId: string, connectionId: string): Promise<boolean>
  /** INTERNAL (future check runner): sealed ciphertext. Must never be used by a route. */
  getConnectionSecrets(
    userId: string,
    projectId: string,
    connectionId: string,
  ): Promise<string | null>
  /**
   * INTERNAL (check runner only, never used by a route): what a run needs, including the sealed
   * secrets. Null when the connection no longer exists.
   */
  getConnectionForRun(
    userId: string,
    projectId: string,
    connectionId: string,
  ): Promise<RunnableConnection | null>
  /** Records the results of one run. False when the connection no longer exists. */
  insertCheckResults(
    userId: string,
    projectId: string,
    connectionId: string,
    results: NewCheckResult[],
  ): Promise<boolean>
  /** Latest result per (connection, check) of the project. Null when the project does not exist. */
  latestCheckResults(userId: string, projectId: string): Promise<CheckResultRecord[] | null>

  /** Null when the project does not exist. */
  getPath(userId: string, projectId: string): Promise<PathRecord | null>
  /**
   * Atomically replaces the whole path. Returns false when the project does not exist; throws
   * `ValidationError` when a node references a connection that is not in this project or has
   * another integration.
   */
  replacePath(userId: string, projectId: string, path: PathRecord): Promise<boolean>
}
